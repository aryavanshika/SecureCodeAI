def normalize_language(language: str) -> str:
    """Normalizes language string to a standard identifier."""
    lang = (language or "").strip().lower()
    if lang in ["py", "python"]:
        return "python"
    elif lang in ["js", "javascript", "node", "ts", "jsx", "tsx"]:
        return "javascript"
    elif lang in ["java"]:
        return "java"
    elif lang in ["c++", "cpp", "c", "h", "hpp"]:
        return "cpp"
    return "python"


def get_demo_snippet(language: str) -> str:
    """Returns a realistic vulnerable code snippet for testing and demos."""
    norm = normalize_language(language)
    return DEMO_SNIPPETS.get(norm, DEMO_SNIPPETS["python"])


def _is_comment_line(line: str, lang: str) -> bool:
    """Detects whether a line is purely a comment in the given language."""
    clean = line.strip()
    if not clean:
        return True
    if lang == "python":
        return clean.startswith("#") or clean.startswith(('"""', "'''"))
    else:
        return clean.startswith("//") or clean.startswith("/*") or clean.startswith("*")


