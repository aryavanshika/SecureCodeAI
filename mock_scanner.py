def _is_fp_hardcoded_secret(line: str) -> bool:
    """Filters out common false positives for hardcoded secrets."""
    lowered = line.lower()
    # Reject environment variable lookups
    if any(env_call in lowered for env_call in [
        "os.getenv", "os.environ", "process.env", "system.getenv",
        "getenv(", "config.get", "settings.get", "vault"
    ]):
        return True
    # Reject obvious dummy placeholder values
    if any(dummy in lowered for dummy in DUMMY_CREDENTIAL_KEYWORDS):
        return True
    # Reject empty or very short values
    if '""' in line or "''" in line:
        return True
    return False


def _is_fp_command_injection(line: str) -> bool:
    """Filters out safe command invocations."""
    # If explicitly shell=False, it is protected from shell meta-character injection
    if re.search(r"shell\s*=\s*False", line, re.IGNORECASE):
        return True
    # Pure static commands with no string concatenation/formatting
    if re.search(r"os\.system\s*\(\s*['\"][a-zA-Z0-9_\-\s]+['\"]\s*\)", line):
        return True
    return False


def _is_fp_sql_injection(line: str) -> bool:
    """Filters out safe parameterized SQL queries."""
    # Check for safe parameterized placeholders without string interpolation/concatenation
    if re.search(r"cursor\.execute\s*\(\s*['\"][^'\"]+%s[^'\"]*['\"]\s*,\s*\(", line):
        return True
    if re.search(r"cursor\.execute\s*\(\s*['\"][^'\"]+\?[^'\"]*['\"]\s*,\s*\[", line):
        return True
    # Simple static queries with no formatting or variables
    if re.search(r"execute\s*\(\s*['\"][^'%$+{}]*['\"]\s*\)", line) and "+" not in line:
        return True
    return False


def _is_fp_debug_mode(line: str) -> bool:
    """Filters out debug variables explicitly disabled or safely read."""
    if re.search(r"debug\s*=\s*False\b", line, re.IGNORECASE):
        return True
    if re.search(r"os\.getenv\s*\(.*debug", line, re.IGNORECASE):
        return True
    return False


def _is_fp_xss(line: str) -> bool:
    """Filters out sanitized DOM assignments."""
    if "dompurify" in line.lower() or "sanitize" in line.lower() or "escape(" in line.lower():
        return True
    return False


def _is_fp_deserialization(line: str) -> bool:
    """Filters out safe YAML and JSON deserializers."""
    if "safe_load" in line.lower() or "safeloader" in line.lower():
        return True
    return False


def _is_fp_path_traversal(line: str) -> bool:
    """Filters out sanitized file paths."""
    if "os.path.basename" in line or "path.basename" in line or "secure_filename" in line:
        return True
    return False


